import { useState } from 'react';
import { useTranslation } from 'react-i18next';

import type { EnterpriseMcpActivationFacts, EnterpriseMcpMetadataTool } from '../../api/domains/extensions';

function configurationText(
  configuration: NonNullable<EnterpriseMcpActivationFacts['configuration']>,
): string {
  const parts: string[] = [];
  if (configuration.transport) parts.push(configuration.transport);
  if (configuration.command) parts.push(configuration.command);
  if (Array.isArray(configuration.args)) parts.push(configuration.args.join(' '));
  else if (configuration.args) parts.push(configuration.args);
  if (Array.isArray(configuration.scopes)) parts.push(configuration.scopes.join(', '));
  else if (configuration.scopes) parts.push(configuration.scopes);
  if (configuration.headers && typeof configuration.headers === 'object') {
    parts.push(Object.entries(configuration.headers).map(([name, value]) => `${name} ${value}`).join(', '));
  } else if (typeof configuration.headers === 'string') {
    parts.push(configuration.headers);
  }
  return parts.filter(Boolean).join(' · ');
}

function ActivationFacts({ tool }: { tool: EnterpriseMcpMetadataTool }) {
  const { t } = useTranslation();
  const activation = tool.activation;
  if (!activation) return null;
  const configText = activation.configuration ? configurationText(activation.configuration) : '';
  const credentialSet = activation.configuration?.credential === 'set';
  if (
    !activation.endpoint
    && !activation.package
    && !activation.permissions?.length
    && !configText
    && !credentialSet
  ) {
    return null;
  }
  return (
    <dl className="ws-mcp-activation" aria-label={t('enterprise.tools.mcpActivationFacts', 'Activation being approved')}>
      {activation.endpoint ? (
        <div>
          <dt>{t('enterprise.tools.mcpActivationEndpoint', 'Endpoint')}</dt>
          <dd>{activation.endpoint}</dd>
        </div>
      ) : null}
      {activation.package ? (
        <div>
          <dt>{t('enterprise.tools.mcpActivationPackage', 'Package')}</dt>
          <dd>{activation.package}</dd>
        </div>
      ) : null}
      {activation.permissions?.length ? (
        <div>
          <dt>{t('enterprise.tools.mcpActivationPermissions', 'Permissions')}</dt>
          <dd>{activation.permissions.join(', ')}</dd>
        </div>
      ) : null}
      {configText ? (
        <div>
          <dt>{t('enterprise.tools.mcpActivationConfiguration', 'Configuration')}</dt>
          <dd>{configText}</dd>
        </div>
      ) : null}
      {credentialSet ? (
        <div>
          <dt>{t('enterprise.tools.mcpActivationCredential', 'Credential')}</dt>
          <dd>{t('enterprise.tools.mcpActivationCredentialSet', 'Set')}</dd>
        </div>
      ) : null}
    </dl>
  );
}

function PlatformDefaultPurpose({ serverName, tool }: { serverName: string; tool: EnterpriseMcpMetadataTool }) {
  const { t } = useTranslation();
  let host = '';
  if (tool.activation?.endpoint) {
    try {
      host = new URL(tool.activation.endpoint).host;
    } catch {
      // Non-URL endpoints still have the connection label.
    }
  }
  const connection = serverName && host && serverName !== host
    ? t('enterprise.tools.mcpConnectionWithHost', { name: serverName, host, defaultValue: '{{name}} ({{host}})' })
    : serverName || host;
  return (
    <>
      <p className="ws-mcp-approved-purpose-text">
        {t('enterprise.tools.mcpDefaultPurpose', {
          connection,
          tool: tool.tool_name,
          defaultValue: 'Tool {{tool}} is provided by {{connection}}. The assistant sees only the default description generated by the platform; the provider’s original description is not used.',
        })}
      </p>
      <details className="ws-mcp-raw-evidence">
        <summary>{t('enterprise.tools.mcpAssistantOriginal', 'Text shown to the assistant')}</summary>
        <pre>{tool.canonical_description}</pre>
      </details>
    </>
  );
}

interface McpMetadataReviewPanelProps {
  serverName: string;
  tools: EnterpriseMcpMetadataTool[];
  busyTool: string | null;
  onReview: (
    tool: EnterpriseMcpMetadataTool,
    decision: 'approve' | 'reject',
    canonicalDescription: string,
  ) => Promise<boolean> | boolean | void;
}

export function McpMetadataReviewPanel({
  serverName,
  tools,
  busyTool,
  onReview,
}: McpMetadataReviewPanelProps) {
  const { t } = useTranslation();
  const [drafts, setDrafts] = useState<Record<string, string>>({});
  // G4b r2/final: an approved tool can still be revoked (the existing reject
  // decision) or have its purpose edited (the existing approve-with-edited-
  // purpose path); both reuse the existing review endpoint. Edit mode is left
  // only after the review request SUCCEEDS — on an error the editor and the
  // draft stay — and 取消 leaves without sending anything.
  const [editingToolId, setEditingToolId] = useState<string | null>(null);
  const submitReview = (tool: EnterpriseMcpMetadataTool, decision: 'approve' | 'reject', draft: string) => {
    void (async () => {
      const ok = await onReview(tool, decision, draft);
      if (ok !== false) setEditingToolId(null);
    })();
  };

  return (
    <section className="ws-mcp-review" aria-label={`${serverName} metadata review`}>
      <div className="ws-mcp-review-heading">
        <strong>{t('enterprise.tools.mcpMetadataReview', 'Metadata review')}</strong>
        <span>{t('enterprise.tools.mcpMetadataAdminOnly', 'Administrator-only evidence')}</span>
      </div>
      {tools.length === 0 ? (
        <div className="ws-tools-empty">
          {t('enterprise.tools.noMcpMetadata', 'No MCP tool metadata found.')}
        </div>
      ) : (
        <div className="ws-mcp-review-list">
          {tools.map((tool) => {
            const previous = tool.reviewed_fingerprint
              && tool.reviewed_fingerprint !== tool.metadata_fingerprint
              ? tool.reviewed_fingerprint
              : null;
            const draft = drafts[tool.tool_id] ?? tool.canonical_description;
            const busy = busyTool === tool.tool_id;
            const editingApproved = tool.runtime_approved && editingToolId === tool.tool_id;
            return (
              <article key={tool.tool_id} className="ws-mcp-review-card">
                <div className="ws-tools-row-between">
                  <div>
                    <strong>{tool.display_name}</strong>
                    {tool.tool_name !== tool.display_name ? (
                      <div className="ws-tools-tiny-muted">{tool.tool_name}</div>
                    ) : null}
                  </div>
                  <span className={`ws-mcp-trust-badge ${tool.runtime_approved ? 'approved' : 'blocked'}`}>
                    {tool.runtime_approved
                      ? t('enterprise.tools.mcpRuntimeApproved', 'Runtime approved')
                      : t('enterprise.tools.mcpRuntimeBlocked', 'Runtime blocked')}
                  </span>
                </div>
                <div className="ws-mcp-review-meta">
                  <span>{t(`enterprise.tools.mcpTrustStatus.${tool.trust_status}`, tool.trust_status)}</span>
                  <span>{t(`enterprise.tools.mcpTrustTier.${tool.trust_tier}`, tool.trust_tier)}</span>
                </div>
                <ActivationFacts tool={tool} />
                <details className="ws-mcp-raw-evidence">
                  <summary>{t('enterprise.tools.mcpVersionDetails', 'View version ID')}</summary>
                  <dl className="ws-mcp-activation">
                    <div>
                      <dt>{t('enterprise.tools.mcpCurrentVersion', 'Current version')}</dt>
                      <dd><code>{tool.metadata_fingerprint}</code></dd>
                    </div>
                    {previous ? (
                      <div>
                        <dt>{t('enterprise.tools.mcpPreviouslyApproved', 'Previously approved')}</dt>
                        <dd><code>{previous}</code></dd>
                      </div>
                    ) : null}
                  </dl>
                </details>
                {tool.risk_flags.length > 0 ? (
                  <div className="ws-mcp-risk-flags">
                    {tool.risk_flags.map((flag) => <span key={flag}>{t(`enterprise.tools.mcpRisk.${flag}`, flag)}</span>)}
                  </div>
                ) : null}
                {tool.runtime_approved && !editingApproved ? (
                  // G4b r2: once approved, the purpose is shown read-only with the
                  // revoke and edit actions; if the remote metadata drifts, the
                  // fingerprint no longer matches and the review pair returns.
                  <div className="ws-mcp-canonical-field" data-testid="mcp-approved-purpose">
                    <span>{t('enterprise.tools.canonicalDescription', 'Canonical runtime description')}</span>
                    {tool.trust_tier === 'platform_generated_reviewed' ? (
                      <PlatformDefaultPurpose serverName={serverName} tool={tool} />
                    ) : (
                      <p className="ws-mcp-approved-purpose-text">{tool.canonical_description}</p>
                    )}
                  </div>
                ) : (
                  <label className="ws-mcp-canonical-field">
                    <span>{t('enterprise.tools.canonicalDescription', 'Canonical runtime description')}</span>
                    <textarea
                      rows={3}
                      maxLength={500}
                      value={draft}
                      placeholder={t('enterprise.tools.mcpDescriptionPlaceholder', 'Describe what employees may use this tool for.')}
                      onChange={(event) => setDrafts((current) => ({
                        ...current,
                        [tool.tool_id]: event.target.value,
                      }))}
                    />
                  </label>
                )}
                <details className="ws-mcp-raw-evidence">
                  <summary>{t('enterprise.tools.rawRemoteEvidence', 'Provider-supplied description (unverified)')}</summary>
                  <pre>{tool.raw_description}</pre>
                  <pre>{JSON.stringify(tool.raw_schema, null, 2)}</pre>
                </details>
                {tool.runtime_approved && !editingApproved ? (
                  <div className="ws-mcp-review-actions">
                    <button
                      type="button"
                      className="btn btn-secondary btn-sm"
                      onClick={() => setEditingToolId(tool.tool_id)}
                    >
                      {t('enterprise.tools.mcpEditPurpose', 'Edit purpose')}
                    </button>
                    <button
                      type="button"
                      className="btn btn-danger btn-sm"
                      disabled={busy}
                      onClick={() => onReview(tool, 'reject', draft)}
                    >
                      {t('enterprise.tools.mcpRevokeApproval', 'Revoke approval')}
                    </button>
                  </div>
                ) : (
                  <div className="ws-mcp-review-actions">
                    <button
                      type="button"
                      className="btn btn-primary btn-sm"
                      disabled={busy || !draft.trim()}
                      onClick={() => submitReview(tool, 'approve', draft)}
                    >
                      {busy ? t('common.saving', 'Saving...') : t('enterprise.tools.approveFingerprint', 'Approve fingerprint')}
                    </button>
                    <button
                      type="button"
                      className="btn btn-secondary btn-sm"
                      disabled={busy}
                      onClick={() => submitReview(tool, 'reject', draft)}
                    >
                      {t('common.reject', 'Reject')}
                    </button>
                    {editingApproved ? (
                      <button
                        type="button"
                        className="btn btn-secondary btn-sm"
                        disabled={busy}
                        onClick={() => setEditingToolId(null)}
                      >
                        {t('common.cancel', 'Cancel')}
                      </button>
                    ) : null}
                  </div>
                )}
              </article>
            );
          })}
        </div>
      )}
    </section>
  );
}
