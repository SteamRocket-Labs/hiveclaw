@pytest.mark.asyncio
async def test_refresh_growth_report_writes_md_and_history(tmp_path: Path) -> None:
    from app.services.growth_report import refresh_growth_report

    agent_id = uuid4()
    _seed_agent(tmp_path, agent_id)

    report_path = await refresh_growth_report(data_root=tmp_path, agent_id=agent_id, db=None, now=NOW)

    assert report_path == _mem_dir(tmp_path, agent_id) / "control" / "growth_report.md"
    body = report_path.read_text(encoding="utf-8")
    assert "fm-guessing" in body
    assert "复发" in body or "recurred" in body
    assert "返工" in body or "rework" in body
    assert "引用" in body or "citation" in body

    history_path = _mem_dir(tmp_path, agent_id) / "control" / "growth_metrics_history.jsonl"
    lines = [json.loads(line) for line in history_path.read_text(encoding="utf-8").splitlines() if line.strip()]
    assert len(lines) == 1
    assert lines[0]["generated_at"]

    await refresh_growth_report(data_root=tmp_path, agent_id=agent_id, db=None, now=NOW + timedelta(hours=1))
    lines = [json.loads(line) for line in history_path.read_text(encoding="utf-8").splitlines() if line.strip()]
    assert len(lines) == 2


@pytest.mark.asyncio
async def test_growth_db_metrics_feedback_polarity_and_task_volume(tmp_path: Path) -> None:
    """DB-side metrics run against a real engine (no mocks of our own layer)."""
    from sqlalchemy.dialects.postgresql import JSONB
    from sqlalchemy.ext.asyncio import AsyncSession, create_async_engine
    from sqlalchemy.ext.compiler import compiles

    from app.database import Base
    from app.models import import_all_models

    import_all_models()  # register FK target tables in Base.metadata
    from app.models.invocation_span import InvocationSpan
    from app.models.session_feedback import SessionFeedbackEvent
    from app.services.growth_report import build_growth_db_metrics

    @compiles(JSONB, "sqlite")
    def _jsonb_as_json(_type, _compiler, **_kw):  # real engine, sqlite renders JSONB as JSON
        return "JSON"

    engine = create_async_engine("sqlite+aiosqlite://")
    async with engine.begin() as conn:
        await conn.run_sync(
            lambda sync_conn: Base.metadata.create_all(
                sync_conn, tables=[SessionFeedbackEvent.__table__, InvocationSpan.__table__]
            )
        )

    agent_id = uuid4()
    tenant_id = uuid4()
    async with AsyncSession(engine) as db:
        db.add(
            SessionFeedbackEvent(
                tenant_id=tenant_id,
                agent_id=agent_id,
                session_id=uuid4(),
                user_id=uuid4(),
                label="useful",
                reason="",
                created_at=NOW - timedelta(days=1),
            )
        )
        db.add(
            SessionFeedbackEvent(
                tenant_id=tenant_id,
                agent_id=agent_id,
                session_id=uuid4(),
                user_id=uuid4(),
                label="misleading",
                reason="",
                created_at=NOW - timedelta(days=20),
            )
        )
        db.add(
            InvocationSpan(
                tenant_id=tenant_id,
                agent_id=agent_id,
                trace_id=str(uuid4()),
                span_id=str(uuid4()),
                span_type="invocation",
                name="chat",
                status="ok",
                started_at=NOW - timedelta(days=1),
                duration_ms=1200.0,
            )
        )
        await db.commit()

        metrics = await build_growth_db_metrics(db=db, agent_id=agent_id, now=NOW)

    polarity = metrics["feedback_polarity"]
    assert polarity["recent"]["useful"] == 1
    assert polarity["recent"]["misleading"] == 0
    assert polarity["previous"]["misleading"] == 1
    volume = metrics["task_volume"]
    assert volume["recent_invocations"] == 1
    await engine.dispose()


